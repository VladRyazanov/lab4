def area(a):
    """
    Вычисляет площадь квадрата по длине его стороны

    Параметры:
        a (float | int): сторона квадрата. Должна быть неотрицательным числом

    Возвращаемое значение:
        float | int: площадь квадрата.

    Пример вызова:
        area(4)
        16
    """
    return a * a


